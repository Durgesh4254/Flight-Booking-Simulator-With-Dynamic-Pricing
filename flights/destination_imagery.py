def get_destination_image(code: str, category: str = 'CITY') -> str:
    """Returns the curated landmark photo for an airport code, with robust category-aware fallback."""
    meta = DESTINATION_METADATA.get(code.upper())
    if meta and meta.get("image"):
        return meta["image"]
    return CATEGORY_DEFAULT_IMAGES.get(category.upper(), "https://images.unsplash.com/photo-1436491865332-7a61a109cc05?w=800&auto=format&fit=crop&q=80")

def get_destination_attractions(code: str, city: str = "") -> list:
    """Returns top curated landmark highlights for an airport."""
    meta = DESTINATION_METADATA.get(code.upper())
    if meta and meta.get("attractions"):
        return meta["attractions"]
    city_name = city.split('/')[0].strip() if city else code
    return [f"{city_name} City Center", f"Historic {city_name}", f"Scenic {city_name} Landmarks"]

def get_destination_season(code: str, default_season: str = "Oct - Apr") -> str:
    """Returns the prime travel season for an airport."""
    meta = DESTINATION_METADATA.get(code.upper())
    if meta and meta.get("season"):
        return meta["season"]
    return default_season or "Oct - Apr"
